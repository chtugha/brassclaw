"""Pinned Linux/amd64 -> Apple Silicon image for the existing Modal builder."""
from pathlib import Path
import hashlib
import base64
import json
import shlex

RUST = "1.96.0"
TARGET = "aarch64-apple-darwin"
BASE = "rust@sha256:811d6caab4a84e6148c8722128993c1caf152156868b2b66f3a26af189b0dad8"
OSXCROSS = "27d21e4977c9751d01199c7a226a6faf494c3dd9"
OSXCROSS_SHA = "c94952432565db84f1b3a9e4ba3d44344b1464fcbeb8c7580ab9db1e7c22834a"
SDK_VERSION = "26.5"
DEPLOYMENT = "14.0"  # The bundled PostgreSQL server requires macOS 14.
PREFIX = "/opt/osxcross/target"
PATH = PREFIX + "/bin:/usr/lib/llvm-19/bin:/usr/local/cargo/bin:/usr/local/sbin:/usr/local/bin:/usr/sbin:/usr/bin:/sbin:/bin"


def configuration(sdk):
    sdk = Path(sdk).resolve(strict=True)
    if sdk.name != f"MacOSX{SDK_VERSION}.sdk.tar.gz":
        raise ValueError("Use the unrenamed SDK generated by OSXCross's macOS packager")
    with sdk.open("rb") as stream:
        sha = hashlib.file_digest(stream, "sha256").hexdigest()
    return {"rust": RUST, "target": TARGET, "base": BASE, "osxcross_commit": OSXCROSS,
            "osxcross_sha256": OSXCROSS_SHA, "sdk_version": SDK_VERSION,
            "sdk_sha256": sha, "deployment_target": DEPLOYMENT,
            "debian_snapshot": "20260701T000000Z", "llvm": "19"}


def image(sdk, config):
    import modal
    root = Path(__file__).resolve().parent
    sdk_dest = f"/opt/osxcross/tarballs/MacOSX{SDK_VERSION}.sdk.tar.gz"
    sources = 'Types: deb\nURIs: https://snapshot.debian.org/archive/debian/20260701T000000Z/\nSuites: trixie\nComponents: main\nSigned-By: /usr/share/keyrings/debian-archive-keyring.gpg\nCheck-Valid-Until: no\n'
    sources += "\nTypes: deb\nURIs: https://snapshot.debian.org/archive/debian-security/20260701T000000Z/\nSuites: trixie-security\nComponents: main\nSigned-By: /usr/share/keyrings/debian-archive-keyring.gpg\nCheck-Valid-Until: no\n"
    env = {"PATH": PATH, "MACOSX_DEPLOYMENT_TARGET": DEPLOYMENT,
           "SDKROOT": f"{PREFIX}/SDK/MacOSX{SDK_VERSION}.sdk",
           "CARGO_TARGET_AARCH64_APPLE_DARWIN_LINKER": f"{PREFIX}/bin/aarch64-apple-darwin25.5-clang",
           "CARGO_BUILD_TARGET": TARGET,
           "CC_aarch64_apple_darwin": f"{PREFIX}/bin/aarch64-apple-darwin25.5-clang",
           "CXX_aarch64_apple_darwin": f"{PREFIX}/bin/aarch64-apple-darwin25.5-clang++",
           "AR_aarch64_apple_darwin": f"{PREFIX}/bin/aarch64-apple-darwin25.5-ar",
           "RANLIB_aarch64_apple_darwin": f"{PREFIX}/bin/aarch64-apple-darwin25.5-ranlib"}
    return (modal.Image.from_registry(BASE, add_python="3.13")
        .env({"PATH": PATH})
        .run_commands("printf %s " + base64.b64encode(sources.encode()).decode() + " | base64 -d > /etc/apt/sources.list.d/debian.sources")
        .apt_install("build-essential", "pkg-config", "libssl-dev", "cmake", "clang-19", "llvm-19", "lld-19",
                     "libclang-19-dev", "git", "curl", "ca-certificates", "rsync", "patch", "xz-utils", "bzip2", "cpio", "file")
        .run_commands(f"mkdir -p /opt/osxcross && curl -fLsS https://codeload.github.com/tpoechtrager/osxcross/tar.gz/{OSXCROSS} -o /tmp/osxcross.tar.gz",
                      f"echo '{OSXCROSS_SHA}  /tmp/osxcross.tar.gz' | sha256sum -c -",
                      "tar xzf /tmp/osxcross.tar.gz --strip-components=1 -C /opt/osxcross")
        .add_local_file(sdk, sdk_dest, copy=True)
        .run_commands(f"echo '{config['sdk_sha256']}  {sdk_dest}' | sha256sum -c -",
                      f"rustup target add {TARGET} --toolchain {RUST}",
                      f"rustup component add clippy rustfmt --toolchain {RUST}")
        .workdir("/opt/osxcross")
        .run_commands("timeout 1200 env JOBS=2 UNATTENDED=1 BUILD_FLAVOR=llvm ENABLE_REPLACEMENT_LIPO=0 ENABLE_ARCHS=arm64 OSX_VERSION_MIN=14.0 SDK_VERSION=26.5 ./build.sh")
        .env(env)
        .run_commands("mkdir -p /opt/brassclaw", "rustc -Vv > /opt/brassclaw/rust.txt",
                      "dpkg-query -W > /opt/brassclaw/packages.txt",
                      "clang --version > /opt/brassclaw/clang.txt",
                      "ld64.lld --version > /opt/brassclaw/linker.txt",
                      "osxcross-conf > /opt/brassclaw/osxcross.txt",
                      "printf %s " + shlex.quote(json.dumps(config, sort_keys=True)) + " > /opt/brassclaw/toolchain.json")
        .add_local_file(root / "modal_source_sync.py", "/opt/brassclaw/modal_source_sync.py", copy=True)
        .add_local_file(root / "modal_build_worker.py", "/opt/brassclaw/modal_build_worker.py", copy=True))
