/// Validate the complete declared inventory against the compiled byte set.
/// A disposition is source selection data, never approval or a Tool grant.
pub(super) fn additional_drafts() -> Result<Vec<ComponentRevisionDraft>, RebornBuildError> {
    let inventory = brassclaw_skills::value_contract::strict_json(
        INVENTORY,
        brassclaw_skills::value_contract::EXECUTION_DATA_LIMITS,
    )
    .map_err(|_| invalid())?;
    if inventory.as_object().is_none_or(|v| v.len() != 3)
        || inventory["format"] != "brassclaw-prefix-source-inventory/1"
        || inventory["release"]
            .as_str()
            .is_none_or(|s| s.trim().is_empty())
    {
        return Err(invalid());
    }
    let rows = inventory["sources"].as_array().ok_or_else(invalid)?;
    let content: std::collections::BTreeMap<_, _> =
        GUIDES.iter().chain(DOCUMENTS.iter()).copied().collect();
    if rows.len() != content.len() || content.len() != GUIDES.len() + DOCUMENTS.len() {
        return Err(invalid());
    }
    let mut seen = std::collections::BTreeSet::new();
    let mut drafts = Vec::new();
    for row in rows {
        let path = row["path"].as_str().ok_or_else(invalid)?;
        let disposition = row["disposition"].as_str().ok_or_else(invalid)?;
        let reason = row["reason"]
            .as_str()
            .filter(|s| !s.trim().is_empty())
            .ok_or_else(invalid)?;
        if row.as_object().is_none_or(|v| v.len() != 4)
            || row["kind"] != "document"
            || !seen.insert(path)
            || !matches!(
                disposition,
                "included" | "historical" | "superseded" | "development-only"
            )
        {
            return Err(invalid());
        }
        let text = *content.get(path).ok_or_else(invalid)?;
        if text.trim().is_empty() {
            return Err(invalid());
        }
        // Existing core identities/definitions and compatibility projections
        // remain unchanged. New records have no editable legacy projection.
        if GUIDES.iter().any(|(core, _)| *core == path) {
            continue;
        }
        drafts.push(ComponentRevisionDraft::from_json(&json!({"format":"component-revision/1",
            "uuid":id(&format!("prefix:document:{path}")),"class_code":17,
            "document":{"format":"packaged-prefix-reference/1","path":path,"content":text,"content_sha256":sha(text),
                "coverage":"declared-release-document-inventory/1","disposition":disposition,"reason":reason,
                "authority":"packaged reference data; source selection is not runtime/model quality approval"},
            "dependencies":[],"association":null}).to_string()).map_err(|_| invalid())?);
    }
    Ok(drafts)
}
